def main():
    print(
        "=" * 60
    )

    print(
        "DataPilot Office 多字段 + 多指标统计测试"
    )

    print(
        "=" * 60
    )

    # ========================================================
    # 1. 创建测试 Excel
    # ========================================================

    input_path = Path(
        "office_test.xlsx"
    )

    df = create_test_data()

    df.to_excel(
        input_path,
        index=False,
        sheet_name="销售数据",
    )

    print()
    print(
        f"测试 Excel 已创建：{input_path}"
    )

    print(
        f"原始数据：{len(df)} 行，"
        f"{len(df.columns)} 列"
    )

    print()
    print(
        "原始数据："
    )

    print(
        df.to_string(
            index=False
        )
    )

    # ========================================================
    # 2. 使用 DataPilot 重新读取 Excel
    # ========================================================

    loaded_df = read_office_data(
        input_path
    )

    print()
    print(
        "-" * 60
    )

    print(
        "Excel 读取成功"
    )

    print(
        f"读取结果：{len(loaded_df)} 行，"
        f"{len(loaded_df.columns)} 列"
    )

    # ========================================================
    # 3. 多字段 + 多指标统计
    #
    # 分组：
    # 城市 + 月份
    #
    # 指标：
    # 销售额：
    #   - 合计
    #   - 平均值
    #
    # 订单金额：
    #   - 平均值
    #   - 最大值
    #
    # 订单号：
    #   - 数量
    # ========================================================

    print()
    print(
        "-" * 60
    )

    print(
        "开始执行多字段 + 多指标统计……"
    )

    result_df = group_multi_statistics(
        df=loaded_df,
        group_by=[
            "城市",
            "月份",
        ],
        aggregations={
            "销售额": [
                "sum",
                "mean",
            ],
            "订单金额": [
                "mean",
                "max",
            ],
            "订单号": [
                "count",
            ],
        },
    )

    print()
    print(
        "统计完成。"
    )

    print()
    print(
        "统计结果："
    )

    print(
        result_df.to_string(
            index=False
        )
    )

    # ========================================================
    # 4. 检查输出字段
    # ========================================================

    expected_columns = [
        "城市",
        "月份",
        "销售额_合计",
        "销售额_平均值",
        "订单金额_平均值",
        "订单金额_最大值",
        "订单号_数量",
    ]

    actual_columns = (
        result_df.columns.tolist()
    )

    print()
    print(
        "-" * 60
    )

    print(
        "检查输出字段……"
    )

    assert (
        actual_columns
        == expected_columns
    ), (
        "\n输出字段不符合预期。\n"
        f"预期：{expected_columns}\n"
        f"实际：{actual_columns}"
    )

    print(
        "字段检查通过。"
    )

    # ========================================================
    # 5. 检查分组数量
    #
    # 应该得到：
    #
    # 澳门 + 2026-07
    # 澳门 + 2026-08
    # 珠海 + 2026-07
    # 珠海 + 2026-08
    #
    # 共 4 组
    # ========================================================

    print()
    print(
        "检查分组数量……"
    )

    assert len(
        result_df
    ) == 4, (
        f"预期得到 4 个分组，"
        f"实际得到 {len(result_df)} 个。"
    )

    print(
        "分组数量检查通过。"
    )

    # ========================================================
    # 6. 检查珠海 2026-07
    # ========================================================

    print()
    print(
        "检查珠海 2026-07 的统计结果……"
    )

    zhuhai_july = result_df[
        (
            result_df["城市"]
            == "珠海"
        )
        & (
            result_df["月份"]
            == "2026-07"
        )
    ]

    assert len(
        zhuhai_july
    ) == 1, (
        "没有正确找到"
        "珠海 2026-07 分组。"
    )

    zhuhai_july = (
        zhuhai_july.iloc[0]
    )

    # 销售额：
    # 12000 + 15000 + 18000 = 45000

    assert (
        float(
            zhuhai_july[
                "销售额_合计"
            ]
        )
        == 45000.0
    ), (
        "珠海 2026-07 "
        "销售额合计计算错误。"
    )

    # 平均销售额：
    # 45000 / 3 = 15000

    assert (
        float(
            zhuhai_july[
                "销售额_平均值"
            ]
        )
        == 15000.0
    ), (
        "珠海 2026-07 "
        "销售额平均值计算错误。"
    )

    # 平均订单金额：
    # (4000 + 5000 + 6000) / 3
    # = 5000

    assert (
        float(
            zhuhai_july[
                "订单金额_平均值"
            ]
        )
        == 5000.0
    ), (
        "珠海 2026-07 "
        "订单金额平均值计算错误。"
    )

    # 最大订单金额：
    # 6000

    assert (
        float(
            zhuhai_july[
                "订单金额_最大值"
            ]
        )
        == 6000.0
    ), (
        "珠海 2026-07 "
        "订单金额最大值计算错误。"
    )

    # 订单数量：
    # 3

    assert (
        int(
            zhuhai_july[
                "订单号_数量"
            ]
        )
        == 3
    ), (
        "珠海 2026-07 "
        "订单数量计算错误。"
    )

    print(
        "珠海 2026-07 统计结果正确。"
    )

    # ========================================================
    # 7. 检查澳门 2026-08
    # ========================================================

    print()
    print(
        "检查澳门 2026-08 的统计结果……"
    )

    macau_august = result_df[
        (
            result_df["城市"]
            == "澳门"
        )
        & (
            result_df["月份"]
            == "2026-08"
        )
    ]

    assert len(
        macau_august
    ) == 1, (
        "没有正确找到"
        "澳门 2026-08 分组。"
    )

    macau_august = (
        macau_august.iloc[0]
    )

    # 销售额：
    # 40000 + 44000 + 48000
    # = 132000

    assert (
        float(
            macau_august[
                "销售额_合计"
            ]
        )
        == 132000.0
    ), (
        "澳门 2026-08 "
        "销售额合计计算错误。"
    )

    # 平均销售额：
    # 132000 / 3
    # = 44000

    assert (
        float(
            macau_august[
                "销售额_平均值"
            ]
        )
        == 44000.0
    ), (
        "澳门 2026-08 "
        "销售额平均值计算错误。"
    )

    # 平均订单金额：
    # (10000 + 11000 + 12000) / 3
    # = 11000

    assert (
        float(
            macau_august[
                "订单金额_平均值"
            ]
        )
        == 11000.0
    ), (
        "澳门 2026-08 "
        "订单金额平均值计算错误。"
    )

    # 最大订单金额：
    # 12000

    assert (
        float(
            macau_august[
                "订单金额_最大值"
            ]
        )
        == 12000.0
    ), (
        "澳门 2026-08 "
        "订单金额最大值计算错误。"
    )

    # 订单数量：
    # 3

    assert (
        int(
            macau_august[
                "订单号_数量"
            ]
        )
        == 3
    ), (
        "澳门 2026-08 "
        "订单数量计算错误。"
    )

    print(
        "澳门 2026-08 统计结果正确。"
    )

    # ========================================================
    # 8. 导出统计结果
    # ========================================================

    output_path = (
        "outputs/"
        "DataPilot_办公统计测试结果.xlsx"
    )

    print()
    print(
        "-" * 60
    )

    print(
        "正在导出统计结果……"
    )

    exported_path = (
        export_office_result(
            df=result_df,
            output_path=output_path,
            sheet_name="统计结果",
        )
    )

    print(
        f"Excel 已导出：{exported_path}"
    )

    # ========================================================
    # 9. 检查输出文件
    # ========================================================

    assert Path(
        exported_path
    ).exists(), (
        "Excel 输出文件不存在。"
    )

    # ========================================================
    # 10. 测试完成
    # ========================================================

    print()
    print(
        "=" * 60
    )

    print(
        "全部测试通过！"
    )

    print(
        "DataPilot 已支持："
    )

    print(
        "1. 多字段分组"
    )

    print(
        "2. 多统计字段"
    )

    print(
        "3. 每个字段多个统计指标"
    )

    print(
        "4. 中文统计结果字段"
    )

    print(
        "5. Excel 结果导出"
    )

    print(
        "=" * 60
    )


if __name__ == "__main__":
    main()